func NewSFTJobResource() resource.Resource {
	return &SFTJobResource{}
}

// SFTJobResource manages a supervised fine-tuning job. Jobs are immutable
// once created and run asynchronously; every attribute change forces
// replacement. Track progress via the state attribute on refresh.
type SFTJobResource struct {
	client *client.Client
}

type SFTJobResourceModel struct {
	ID                types.String  `tfsdk:"id"`
	Name              types.String  `tfsdk:"name"`
	DisplayName       types.String  `tfsdk:"display_name"`
	Dataset           types.String  `tfsdk:"dataset"`
	BaseModel         types.String  `tfsdk:"base_model"`
	WarmStartFrom     types.String  `tfsdk:"warm_start_from"`
	OutputModel       types.String  `tfsdk:"output_model"`
	EvaluationDataset types.String  `tfsdk:"evaluation_dataset"`
	Epochs            types.Int64   `tfsdk:"epochs"`
	LearningRate      types.Float64 `tfsdk:"learning_rate"`
	LoraRank          types.Int64   `tfsdk:"lora_rank"`
	BatchSize         types.Int64   `tfsdk:"batch_size"`
	MaxContextLength  types.Int64   `tfsdk:"max_context_length"`
	EarlyStop         types.Bool    `tfsdk:"early_stop"`
	State             types.String  `tfsdk:"state"`
	CreateTime        types.String  `tfsdk:"create_time"`
	CompletedTime     types.String  `tfsdk:"completed_time"`
}

