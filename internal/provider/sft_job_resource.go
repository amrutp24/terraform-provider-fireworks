func (r *SFTJobResource) Configure(ctx context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}
	c, ok := req.ProviderData.(*client.Client)
	if !ok {
		resp.Diagnostics.AddError(
			"Unexpected Resource Configure Type",
			fmt.Sprintf("Expected *client.Client, got: %T.", req.ProviderData),
		)
		return
	}
	r.client = c
}

func (m *SFTJobResourceModel) fromAPI(job *client.SupervisedFineTuningJob) {
	m.ID = types.StringValue(client.ResourceID(job.Name))
	m.Name = types.StringValue(job.Name)
	m.Dataset = types.StringValue(job.Dataset)
	m.State = types.StringValue(job.State)
	m.CreateTime = types.StringValue(job.CreateTime)
	m.CompletedTime = types.StringValue(job.CompletedTime)

	// Optional attributes: only overwrite when the API reports a value.
	if job.DisplayName != "" || !m.DisplayName.IsNull() {
		m.DisplayName = stringOrNull(job.DisplayName)
	}
	if job.BaseModel != "" || !m.BaseModel.IsNull() {
		m.BaseModel = stringOrNull(job.BaseModel)
	}
	if job.WarmStartFrom != "" || !m.WarmStartFrom.IsNull() {
		m.WarmStartFrom = stringOrNull(job.WarmStartFrom)
	}
	if job.EvaluationDataset != "" || !m.EvaluationDataset.IsNull() {
		m.EvaluationDataset = stringOrNull(job.EvaluationDataset)
	}

	// Optional+computed attributes always take the server's value.
	m.OutputModel = stringOrNull(job.OutputModel)
	m.Epochs = int64OrNull(job.Epochs)
	m.LearningRate = float64OrNull(job.LearningRate)
	m.LoraRank = int64OrNull(job.LoraRank)
	m.BatchSize = int64OrNull(job.BatchSize)
	m.MaxContextLength = int64OrNull(job.MaxContextLength)
	m.EarlyStop = types.BoolValue(job.EarlyStop)
}

func float64OrNull(v *float64) types.Float64 {
	if v == nil {
		return types.Float64Null()
	}
	return types.Float64Value(*v)
}

func (r *SFTJobResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var data SFTJobResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}

	hasBase := !data.BaseModel.IsNull() && data.BaseModel.ValueString() != ""
	hasWarm := !data.WarmStartFrom.IsNull() && data.WarmStartFrom.ValueString() != ""
	if hasBase == hasWarm {
		resp.Diagnostics.AddError(
			"Invalid fine-tuning job configuration",
			"Exactly one of base_model or warm_start_from must be set.",
		)
		return
	}

	job := &client.SupervisedFineTuningJob{
		DisplayName:       data.DisplayName.ValueString(),
		Dataset:           data.Dataset.ValueString(),
		BaseModel:         data.BaseModel.ValueString(),
		WarmStartFrom:     data.WarmStartFrom.ValueString(),
		EvaluationDataset: data.EvaluationDataset.ValueString(),
	}
	if !data.OutputModel.IsNull() && !data.OutputModel.IsUnknown() {
		job.OutputModel = data.OutputModel.ValueString()
	}
	if !data.Epochs.IsNull() && !data.Epochs.IsUnknown() {
		job.Epochs = data.Epochs.ValueInt64Pointer()
	}
	if !data.LearningRate.IsNull() && !data.LearningRate.IsUnknown() {
		job.LearningRate = data.LearningRate.ValueFloat64Pointer()
	}
	if !data.LoraRank.IsNull() && !data.LoraRank.IsUnknown() {
		job.LoraRank = data.LoraRank.ValueInt64Pointer()
	}
	if !data.BatchSize.IsNull() && !data.BatchSize.IsUnknown() {
		job.BatchSize = data.BatchSize.ValueInt64Pointer()
	}
	if !data.MaxContextLength.IsNull() && !data.MaxContextLength.IsUnknown() {
		job.MaxContextLength = data.MaxContextLength.ValueInt64Pointer()
	}
	if !data.EarlyStop.IsNull() && !data.EarlyStop.IsUnknown() {
		job.EarlyStop = data.EarlyStop.ValueBool()
	}

	out, err := r.client.CreateSupervisedFineTuningJob(ctx, job)
	if err != nil {
		resp.Diagnostics.AddError("Error creating fine-tuning job", err.Error())
		return
	}

	data.fromAPI(out)
	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

func (r *SFTJobResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var data SFTJobResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}

	job, err := r.client.GetSupervisedFineTuningJob(ctx, data.ID.ValueString())
	if err != nil {
		if client.IsNotFound(err) {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Error reading fine-tuning job", err.Error())
		return
	}

	data.fromAPI(job)
	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

// Update is never called: every attribute is Required/RequiresReplace or
// Computed, so changes always plan as replacement.
func (r *SFTJobResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var data SFTJobResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

func (r *SFTJobResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var data SFTJobResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}

	if err := r.client.DeleteSupervisedFineTuningJob(ctx, data.ID.ValueString()); err != nil && !client.IsNotFound(err) {
		resp.Diagnostics.AddError("Error deleting fine-tuning job", err.Error())
	}
}

func (r *SFTJobResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root("id"), req, resp)
}
